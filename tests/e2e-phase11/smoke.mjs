import { boot, OUT } from './lib.mjs'
const T = await boot()
const { page, check } = T
await page.locator('button[title="Drawing tools"]').click()
await page.waitForTimeout(300)
await page.locator('[data-testid="grp-Lines"]').click()
await page.screenshot({ path: OUT + '/11-flyout.png' })
await page.locator('[data-testid="tool-trend"]').click()
const H = await T.host()
await page.mouse.move(H.x + 300, H.y + 300)
await page.mouse.down()
await page.mouse.move(H.x + 500, H.y + 250, { steps: 8 })
await page.mouse.up()
await page.waitForTimeout(500)
const d = await T.drawings()
check('trend line created', d.length === 1 && d[0].type === 'trend', JSON.stringify(d[0]).slice(0, 200))
await page.screenshot({ path: OUT + '/11-trend.png' })
check('floating bar visible', await page.locator('[data-testid="draw-bar"]').isVisible())
await T.done()
