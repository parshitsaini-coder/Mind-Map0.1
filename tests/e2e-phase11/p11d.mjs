// 360 px phone: toolbar + flyout, tap-tap drawing, floating bar, dialog as a bottom sheet, object tree, indicator dialog, no horizontal overflow
import { boot, OUT } from './lib.mjs'
const T = await boot({ width: 360, height: 740, touch: true })
const { page, check } = T
const noOverflow = async (label) => check(`${label}: no horizontal page overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
await page.screenshot({ path: OUT + '/11d-phone-start.png' })
const drawBtn = page.locator('button[title="Drawing tools"]')
await drawBtn.tap(); await page.waitForTimeout(300)
check('drawing toolbar opens', await page.locator('[role="toolbar"][aria-label="Drawing tools"]').isVisible())
await page.locator('[data-testid="grp-Lines"]').tap()
const fly = page.locator('[role="menu"]')
const fb = await fly.boundingBox()
check('flyout fits inside the 360 px screen', fb && fb.x >= 0 && fb.x + fb.width <= 360, JSON.stringify(fb))
await page.screenshot({ path: OUT + '/11d-phone-flyout.png' })
await page.locator('[data-testid="tool-trend"]').tap()
const H = await T.host()
await page.touchscreen.tap(H.x + 60, H.y + 250); await page.waitForTimeout(200)
await page.touchscreen.tap(H.x + 250, H.y + 180); await page.waitForTimeout(400)
let d = await T.drawings()
check('tap-tap creates a trend line on touch', d.length === 1 && d[0].type === 'trend', String(d.length))
const bar = page.locator('[data-testid="draw-bar"]')
const bb = await bar.boundingBox()
check('floating bar is on screen and not wider than the phone', bb && bb.x >= 0 && bb.x + bb.width <= 361, JSON.stringify(bb))
await page.screenshot({ path: OUT + '/11d-phone-bar.png' })
await page.locator('[data-testid="draw-bar"] [aria-label="Settings"]').tap(); await page.waitForTimeout(300)
const dlg = await page.locator('[data-testid="draw-dialog"] > div').boundingBox()
check('settings dialog fits the screen (bottom sheet)', dlg && dlg.x >= 0 && dlg.x + dlg.width <= 361 && dlg.y >= 0 && dlg.y + dlg.height <= 741, JSON.stringify(dlg))
await page.screenshot({ path: OUT + '/11d-phone-dialog.png' })
await page.locator('[data-testid="in-width"]').selectOption('4')
check('dialog control works on touch layout', (await T.drawings())[0].width === 4)
await page.locator('[data-testid="dlg-ok"]').tap(); await page.waitForTimeout(200)
await page.locator('[data-testid="tree-btn"]').tap(); await page.waitForTimeout(300)
const tb = await page.locator('[data-testid="object-tree"]').boundingBox()
check('object tree fits the phone', tb && tb.x >= 0 && tb.x + tb.width <= 361, JSON.stringify(tb))
await page.screenshot({ path: OUT + '/11d-phone-tree.png' })
await page.locator('[data-testid="tree-btn"]').tap()
await noOverflow('drawing UI')
// position tool
await page.locator('[data-testid="grp-Trading tools"]').tap(); await page.locator('[data-testid="tool-long"]').tap()
await page.touchscreen.tap(H.x + 120, H.y + 300); await page.waitForTimeout(400)
check('long position placed by one tap', (await T.drawings()).some((x) => x.type === 'long'))
await page.screenshot({ path: OUT + '/11d-phone-long.png' })
// indicators
await page.locator('button[title="Indicators"]').tap(); await page.waitForTimeout(300)
await page.locator('button[title]:has-text("Volume")').first().tap(); await page.waitForSelector('[data-testid="ind-dialog"]')
const ib = await page.locator('[data-testid="ind-dialog"] > div').boundingBox()
check('indicator dialog fits the phone', ib && ib.x >= 0 && ib.x + ib.width <= 361 && ib.y >= 0 && ib.y + ib.height <= 741, JSON.stringify(ib))
await page.screenshot({ path: OUT + '/11d-phone-ind-dialog.png' })
await page.locator('[data-testid="idlg-ok"]').tap(); await page.waitForTimeout(200)
await page.locator('[role="dialog"][aria-label="Indicators"] [aria-label="Close"]').tap().catch(() => {})
await page.waitForTimeout(300)
await page.screenshot({ path: OUT + '/11d-phone-final.png' })
await noOverflow('with indicators')
await T.done()
